"use client";

import { useState } from "react";
import { CopyButton } from "@/components/CopyButton";
import type { CoverLetterOutput } from "@/lib/types";

interface RoleProps {
  mode: "role";
  resume: string;
  jd: string;
  intakeAnswers: { question: string; answer: string }[];
}

interface CompanyProps {
  mode: "company";
  resume: string;
  companyContent: string;
  companyUrl: string;
  intakeAnswers: { question: string; answer: string }[];
}

type Props = RoleProps | CompanyProps;

async function downloadCoverLetterDocx(coverLetterText: string): Promise<void> {
  const { Document, Paragraph, TextRun, Packer, AlignmentType } = await import("docx");

  const FONT = "Calibri";
  const BODY_PT = 11;

  const paragraphs = coverLetterText.split("\n").map(
    (line) =>
      new Paragraph({
        alignment: AlignmentType.LEFT,
        spacing: { after: line.trim() === "" ? 80 : 0 },
        children: [
          new TextRun({
            text: line,
            font: FONT,
            size: BODY_PT * 2,
          }),
        ],
      }),
  );

  const doc = new Document({
    title: "Cover Letter — Resume Verdict",
    description: "Cover letter generated by Resume Verdict",
    styles: {
      default: {
        document: {
          run: { font: FONT, size: BODY_PT * 2 },
        },
      },
    },
    sections: [
      {
        properties: {
          page: {
            margin: { top: 1440, bottom: 1440, left: 1440, right: 1440 },
          },
        },
        children: paragraphs,
      },
    ],
  });

  const blob = await Packer.toBlob(doc);
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = "cover-letter-resume-verdict.docx";
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

export function CoverLetterSection(props: Props) {
  const [status, setStatus] = useState<"idle" | "loading" | "done" | "error">("idle");
  const [output, setOutput] = useState<CoverLetterOutput | null>(null);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);
  const [docxBusy, setDocxBusy] = useState(false);
  const [docxErr, setDocxErr] = useState<string | null>(null);

  async function generate() {
    setStatus("loading");
    setErrorMsg(null);
    try {
      let body: Record<string, unknown>;
      if (props.mode === "role") {
        body = {
          mode: "role",
          resume: props.resume,
          jd: props.jd,
          intakeAnswers: props.intakeAnswers,
        };
      } else {
        body = {
          mode: "company",
          resume: props.resume,
          companyContent: props.companyContent,
          companyUrl: props.companyUrl,
          intakeAnswers: props.intakeAnswers,
        };
      }

      const res = await fetch("/api/demo/cover-letter", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(body),
      });
      const data = (await res.json()) as {
        coverLetter?: CoverLetterOutput;
        error?: string;
      };
      if (!res.ok || !data.coverLetter) {
        throw new Error(data.error ?? `Request failed (${res.status}).`);
      }
      setOutput(data.coverLetter);
      setStatus("done");
    } catch (err) {
      setErrorMsg(err instanceof Error ? err.message : "An error occurred.");
      setStatus("error");
    }
  }

  async function handleDocxDownload() {
    if (!output) return;
    setDocxBusy(true);
    setDocxErr(null);
    try {
      await downloadCoverLetterDocx(output.coverLetter);
    } catch (e) {
      setDocxErr(e instanceof Error ? e.message : "Download failed.");
    } finally {
      setDocxBusy(false);
    }
  }

  return (
    <section className="flex flex-col gap-3">
      <p className="section-label">Cover Letter</p>

      {status === "idle" && (
        <button
          onClick={generate}
          style={{ minHeight: 44 }}
          className="inline-flex w-full items-center justify-center rounded-lg border border-soft-gray bg-pure-white px-5 py-3 text-sm font-semibold text-carbon-core transition hover:bg-ash-white sm:w-auto"
        >
          Generate Cover Letter
        </button>
      )}

      {status === "loading" && (
        <p className="text-sm text-echo">Writing your cover letter...</p>
      )}

      {status === "error" && (
        <div className="flex flex-col gap-2">
          <p className="rounded-lg border border-forge-red/30 bg-forge-red/10 p-3 text-sm text-forge-red">
            {errorMsg}
          </p>
          <button
            onClick={generate}
            style={{ minHeight: 44 }}
            className="inline-flex w-fit items-center rounded-lg border border-soft-gray bg-pure-white px-5 py-3 text-sm font-semibold text-carbon-core transition hover:bg-ash-white"
          >
            Try again
          </button>
        </div>
      )}

      {status === "done" && output && (
        <div className="flex flex-col gap-4">
          <div className="card-surface flex flex-col gap-3">
            {/* Header row */}
            <div className="flex flex-wrap items-center justify-between gap-2">
              <p className="section-label">Your cover letter</p>
              <CopyButton text={output.coverLetter} />
            </div>

            {/* Cover letter text */}
            <pre className="whitespace-pre-wrap font-sans text-base leading-relaxed text-carbon-core">
              {output.coverLetter}
            </pre>

            {/* Download docx */}
            <div className="flex flex-col gap-1">
              <button
                onClick={handleDocxDownload}
                disabled={docxBusy}
                style={{ minHeight: 44 }}
                className="inline-flex w-fit items-center rounded-lg border border-soft-gray bg-pure-white px-5 py-3 text-sm font-semibold text-carbon-core transition hover:bg-ash-white disabled:opacity-60"
              >
                {docxBusy ? "Building .docx..." : "Download as .docx"}
              </button>
              {docxErr && (
                <p className="text-xs text-forge-red" role="alert">
                  {docxErr}
                </p>
              )}
            </div>
          </div>

          {/* Key evidence */}
          {output.keyEvidence.length > 0 && (
            <div className="card-surface">
              <p className="section-label mb-2">Evidence used</p>
              <ul className="ml-5 list-disc text-sm leading-relaxed text-carbon-core">
                {output.keyEvidence.map((e, i) => (
                  <li key={i}>{e}</li>
                ))}
              </ul>
            </div>
          )}

          {/* Tone check */}
          <p className="text-xs text-echo">{output.toneCheck}</p>
        </div>
      )}
    </section>
  );
}
